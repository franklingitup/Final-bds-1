package cluster

import (
	"fmt"
	"net/url"
	"strconv"
	"strings"
	"text/template"
)

const (
	defaultAgentNamespace           = "platform-agent"
	defaultAgentImage               = "platform-agent:0.1.0"
	defaultMetricsCollectorEnabled  = "true"
	defaultMetricsCollectorInterval = "60s"
	defaultLogShipperEnabled        = "true"
	defaultLogShipperBatchInterval  = "5s"
	defaultLogShipperMaxTailedPods  = "50"
)

// InstallManifestGenerator renders the self-contained manifest used to install
// an agent into an existing cluster.
type InstallManifestGenerator struct {
	namespace                   string
	image                       string
	defaultControlPlaneEndpoint string
}

// NewInstallManifestGenerator creates a generator with optional defaults.
// The controlPlaneEndpoint is the server-side default for the address agents
// should use to reach the control plane. This is NOT the browser-facing gateway
// URL — it's the URL reachable from inside customer Kubernetes clusters.
func NewInstallManifestGenerator(namespace, image, controlPlaneEndpoint string) *InstallManifestGenerator {
	if namespace == "" {
		namespace = defaultAgentNamespace
	}
	if image == "" {
		image = defaultAgentImage
	}
	return &InstallManifestGenerator{
		namespace:                   namespace,
		image:                       image,
		defaultControlPlaneEndpoint: controlPlaneEndpoint,
	}
}

// DefaultControlPlaneEndpoint returns the configured default endpoint, if any.
func (g *InstallManifestGenerator) DefaultControlPlaneEndpoint() string {
	return g.defaultControlPlaneEndpoint
}

// ResolveControlPlaneEndpoint returns the provided endpoint if non-empty,
// otherwise falls back to the configured default. Returns an error if neither
// is available.
func (g *InstallManifestGenerator) ResolveControlPlaneEndpoint(override string) (string, error) {
	endpoint := strings.TrimSpace(override)
	if endpoint == "" {
		endpoint = g.defaultControlPlaneEndpoint
	}
	if endpoint == "" {
		return "", fmt.Errorf("controlPlaneEndpoint is required: set CONTROL_PLANE_PUBLIC_URL or provide it explicitly")
	}
	return normalizeControlPlaneEndpoint(endpoint)
}

func (g *InstallManifestGenerator) ManifestURL(controlPlaneEndpoint, token string) (string, error) {
	endpoint, err := g.ResolveControlPlaneEndpoint(controlPlaneEndpoint)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf(
		"%s/v1/agent-install/%s/manifest.yaml",
		endpoint,
		url.PathEscape(token),
	), nil
}

func (g *InstallManifestGenerator) Generate(token, controlPlaneEndpoint string) (string, error) {
	endpoint, err := g.ResolveControlPlaneEndpoint(controlPlaneEndpoint)
	if err != nil {
		return "", err
	}

	data := struct {
		Namespace               string
		Image                   string
		Token                   string
		ControlPlaneEndpoint    string
		MetricsCollectorEnabled string
		MetricsInterval         string
		LogShipperEnabled       string
		LogShipperBatchInterval string
		MaxTailedPods           string
	}{
		Namespace:               g.namespace,
		Image:                   g.image,
		Token:                   strconv.Quote(token),
		ControlPlaneEndpoint:    strconv.Quote(endpoint),
		MetricsCollectorEnabled: defaultMetricsCollectorEnabled,
		MetricsInterval:         defaultMetricsCollectorInterval,
		LogShipperEnabled:       defaultLogShipperEnabled,
		LogShipperBatchInterval: defaultLogShipperBatchInterval,
		MaxTailedPods:           defaultLogShipperMaxTailedPods,
	}

	tmpl, err := template.New("agent-install").Parse(agentInstallManifestTemplate)
	if err != nil {
		return "", fmt.Errorf("parse agent install manifest: %w", err)
	}
	var out strings.Builder
	if err := tmpl.Execute(&out, data); err != nil {
		return "", fmt.Errorf("render agent install manifest: %w", err)
	}
	return out.String(), nil
}

func normalizeControlPlaneEndpoint(raw string) (string, error) {
	raw = strings.TrimSpace(raw)
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Scheme == "" || parsed.Host == "" {
		return "", fmt.Errorf("controlPlaneEndpoint must be an absolute HTTP(S) URL")
	}
	if parsed.Scheme != "http" && parsed.Scheme != "https" {
		return "", fmt.Errorf("controlPlaneEndpoint must use HTTP or HTTPS")
	}
	parsed.Path = strings.TrimRight(parsed.Path, "/")
	parsed.RawQuery = ""
	parsed.Fragment = ""
	return strings.TrimRight(parsed.String(), "/"), nil
}

